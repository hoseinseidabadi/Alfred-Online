/** پرسش را با گزینه‌هایش به یک پیام قابل ارسال تبدیل می‌کند. */
export function questionMessage(question: Question): {
  text: string;
  choices?: readonly { value: string; label: string }[];
} {
  return question.choices === undefined
    ? { text: question.prompt }
    : { text: question.prompt, choices: question.choices };
}
