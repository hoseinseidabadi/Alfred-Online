#!/bin/sh
# لیارا با `npm ci` بدون وابستگی‌های توسعه نصب می‌کند، ولی بیلد به آن‌ها
# نیاز دارد: `nest` و `tsc` هر دو devDependency اند. این اسکریپت درست پیش
# از `npm run build` اجرا می‌شود و کمبود را جبران می‌کند.
#
# `prisma` عمداً اینجا نیست — به `dependencies` منتقل شد، چون اسکریپت start
# در **زمان اجرا** `migrate deploy` می‌زند. اگر لیارا روزی پس از بیلد
# devDependency ها را هرس کند، بوت نباید بشکند.
set -e
echo "> نصب وابستگی‌های توسعه برای بیلد..."
npm ci --include=dev
